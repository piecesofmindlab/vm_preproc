function params = preprocAppendModel_GetMetaParams(argNum)
% Usage: params = preprocAppendModel_GetMetaParams(argNum)
% 
% Return preset parameters for preprocAppendModel, i.e. model query
% parameters for models to append. NOTE THAT THIS WORKS SUBSTANTIALLY
% DIFFERENTLY FROM OTHER PREPROC<X>_GETMETAPARAMS FUNCTIONS, in that it
% explicitly relies on the use of a database.
% 
% Different "argNum"s will specify the StimClass of the stimulus for the
% model, as well as the preprocessing sequence, but NOT the experiment name
% / session / training vs validation status; the function
% preprocAppendModel relies on a PreprocessedStimulus input (rather than a
% raw numerical matrix) to fill in those parameters. 
% 
% ML 2013.05

params.class = 'preprocAppendModel';
switch argNum
    case 1
        % RMS contrast, no TF channels
        params.LeftRight = 'Right';
        params.stimToAdd.StimClass = 'RGB';
        params.ppSeqToAdd = {'preprocColorSpace',1,...
                        'preprocRMS',1,...
                        'preprocDownsample',1,...
                        'preprocNormalize',1};
