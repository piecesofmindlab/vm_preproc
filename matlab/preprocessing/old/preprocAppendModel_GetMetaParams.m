        % No-orientation contour contrast, w/ TF channels
        params.LeftRight = 'Right';
        params.stimToAdd.StimClass = 'ObNormals';
        params.ppSeqToAdd = {'preprocNormalGradient',1,...
                        'preprocWavelets_grid',10,...
                        'preprocNonLinearOut',1,...
                        'preprocDownsample',1,...
                        'preprocNormalize',1};
    
